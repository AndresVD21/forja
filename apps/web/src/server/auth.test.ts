// The real Better Auth configuration (create-auth.ts) running on an in-memory database with every migration applied.
import { createRepositories, type Database } from "@forja/db";
import { createTestDb } from "@forja/db/testing";
import { beforeAll, describe, expect, it } from "vitest";
import { createAuth, inviteOnly, type Auth } from "./create-auth";

let db: Database;
let auth: Auth;
let repos: ReturnType<typeof createRepositories>;

beforeAll(async () => {
  db = await createTestDb();
  repos = createRepositories(db);
  auth = createAuth(db, { transactions: false, secret: "test-secret-test-secret-test-secret-123", baseURL: "http://localhost:3000" });
  await repos.allowedEmails.invite("owner@example.test");
});

const signUp = (email: string, password = "correct horse battery") =>
  auth.api.signUpEmail({ body: { email, name: "Test User", password } });

/** Runs a call that must fail and returns the error's status and body, so tests can compare them. */
async function failure(call: () => Promise<unknown>) {
  try {
    await call();
  } catch (error) {
    const e = error as { statusCode?: number; status?: string | number; body?: unknown; message?: string };
    return { status: e.statusCode ?? e.status, body: e.body };
  }
  throw new Error("expected the call to fail");
}

describe("invite-only sign-up", () => {
  it("lets an invited email sign up, with a uuid generated by the database", async () => {
    const result = await signUp("owner@example.test");
    expect(result.user.email).toBe("owner@example.test");
    expect(result.user.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
  });

  it("lets that user sign in with the right password and refuses a wrong one", async () => {
    const ok = await auth.api.signInEmail({ body: { email: "owner@example.test", password: "correct horse battery" } });
    expect(ok.token).toBeTruthy();
    const wrong = await failure(() => auth.api.signInEmail({ body: { email: "owner@example.test", password: "wrong password!!" } }));
    expect(wrong.status).toBeGreaterThanOrEqual(400);
  });

  it("refuses an email that is not invited, and creates no user", async () => {
    const refused = await failure(() => signUp("stranger@example.test"));
    expect(refused.status).toBe(403);
    expect(await repos.allowedEmails.isAllowed("stranger@example.test")).toBe(false);
    await expect(auth.api.signInEmail({ body: { email: "stranger@example.test", password: "correct horse battery" } })).rejects.toBeDefined();
  });

  it("ignores case and surrounding spaces when checking the invite", async () => {
    await repos.allowedEmails.invite("  Friend@Example.TEST ");
    expect(await repos.allowedEmails.isAllowed("friend@example.test")).toBe(true);
    const result = await signUp("FRIEND@example.test");
    expect(result.user.email).toBe("friend@example.test");
  });

  it("answers a non-invited email the same whether or not it already has an account", async () => {
    // "Has an account" but is no longer invited: remove the invitation of an existing user.
    await repos.allowedEmails.revoke("friend@example.test");
    const existing = await failure(() => signUp("friend@example.test"));
    const unknown = await failure(() => signUp("nobody@example.test"));
    expect(existing).toEqual(unknown);
  });
});

describe("inviteOnly (the validateUserInfo guard: the only one a Google sign-in meets)", () => {
  // Every source Better Auth can pass: it must not matter, nobody gets in without an invitation.
  const sources = [
    { action: "create-user", method: "email-password" },
    { action: "create-user", method: "oauth", oauth: { providerId: "google" } },
    { action: "link-account", method: "oauth", oauth: { providerId: "google" } },
    { action: "sign-in", method: "oauth", oauth: { providerId: "google" } },
  ];

  it.each(sources)("refuses a non-invited email ($action, $method)", async (source) => {
    const check = inviteOnly({ isAllowed: async () => false });
    expect(await (check as (a: unknown) => Promise<unknown>)({ user: { email: "stranger@example.test" }, source })).toEqual({
      error: "not_invited",
      errorDescription: "This email cannot create an account.",
    });
  });

  it.each(sources)("accepts an invited email in any case or spacing ($action, $method)", async (source) => {
    const check = inviteOnly({ isAllowed: (email) => repos.allowedEmails.isAllowed(email) });
    for (const email of ["owner@example.test", "  OWNER@Example.TEST "]) {
      expect(await (check as (a: unknown) => Promise<unknown>)({ user: { email }, source })).toBeUndefined();
    }
  });

  it("refuses a missing or non-string email", async () => {
    const check = inviteOnly({ isAllowed: (email) => repos.allowedEmails.isAllowed(email) });
    expect(await check({ user: {} })).toMatchObject({ error: "not_invited" });
    expect(await check({ user: { email: 42 } })).toMatchObject({ error: "not_invited" });
  });

  it("is what the built auth instance uses", async () => {
    const validate = auth.options.user?.validateUserInfo;
    expect(validate).toBeTypeOf("function");
    const call = (email: string) =>
      (validate as (data: unknown, ctx: unknown) => Promise<unknown>)(
        { user: { email }, source: { action: "create-user", method: "oauth", oauth: { providerId: "google" } } },
        {},
      );
    expect(await call("not-invited-google@example.test")).toMatchObject({ error: "not_invited" });
    expect(await call("Owner@example.test")).toBeUndefined();
  });
});
